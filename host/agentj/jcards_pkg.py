"""P432 (#66 Cards phase 2, spec AGENTJ-CARDS-SPEC §7): a card as a plaza package (`.ajpkg` type `card`, PLAZA_PACKAGES).

    <package>/manifest.json   type "card", entry "card/card.json"
              README.md       what the card shows, its buttons, its server (generated by `agentj card pack`)
              card/card.json  the card (every jcards rule)
              card/sample/<data file>   sample data only — never the owner's data folder

`pack` builds that folder from one of the owner's cards (`agentj card pack <id> <folder>`, then `agentj plaza publish
<folder>`, which runs the plaza's two privacy layers and the owner's digest-bound yes). `preflight` is the 上线关键点 check
(Leo: 「关键点达标就允许发出去」) run by pack, publish and install: only those files, a valid card, a card server pinned to a
GitHub commit (Leo Q2), a sample that renders with its template and holds no key, every button message renders under its
label. `install` (from `agentj plaza install`, after the signature / SHA-256 / owner checks of market.py) applies the card
**switched off** and records where it came from in `<state>/cards/plaza.json`; the phone shows the permission
summary (`summary`: the data source, every button's whole message or server call, links, the server's repository and
commit) and switches it on only with that summary's digest (`jcard_perm` → `jcard_set seen`). P432 security review: the
source records and the digest the owner approved live in `<state>/cards/plaza.json` (not `agentperm`) — so an Agent inside
the fence can neither forge a 「官方审核」 record nor switch a plaza card on by editing the switches (`cards()` keeps a plaza
card off unless the approved digest matches the card as it is now); every author string in the summary is one quoted line. A new version (`--replace`)
puts the old one to sleep and is off again until reviewed; `agentj card rollback <id>` brings the newest sleeping version
back, also off. The card's server is never fetched or run by agentj.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import re
import shutil
import tempfile
import unicodedata

from . import jcards, jcards_server, privacy

FILES_OK = ("README.md", "card/card.json")
SOURCES_KEEP = jcards.DORMANT_KEEP + 1
_SEMVER = re.compile(r"\d+(\.\d+){0,2}")


def _semver(v: str) -> str:
    parts = (v.split(".") + ["0", "0"])[:3]
    return ".".join(str(int(x)) for x in parts)


def summary_of(doc: dict) -> dict:
    """What the card can do, language-independent (its digest is what the owner confirms)."""
    d = doc["data"]
    srv = doc.get("server") if isinstance(doc.get("server"), dict) else None
    def btn(a):
        if "call" in a:
            path = next(r["path"] for r in srv["routes"] if r["id"] == a["call"])
            return {"label": a["label"], "call": jcards_server.where(doc, path, "POST")}
        return {"label": a["label"], "prompt": a["prompt"], "draft": bool(a.get("draft"))}
    return {"id": doc["id"], "version": doc["version"], "template": doc["template"],
            "data": {"file": d["file"]} if "file" in d else {"get": jcards_server.where(doc, d["get"])},
            "buttons": [btn(a) for a in doc.get("actions", [])], "itemButtons": [btn(a) for a in doc.get("itemActions", [])],
            "links": [{"label": x["label"], **({"href": x["href"]} if "href" in x else {"jlink": x["jlink"]})} for x in doc.get("links", [])],
            "server": {"port": srv["port"], "routes": srv.get("routes", []), "repo": srv.get("repo"), "ref": srv.get("ref")} if srv else None}


def digest(doc: dict) -> str:
    return hashlib.sha256(json.dumps(summary_of(doc), ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()).hexdigest()[:16]


_T = {"zh": {"file": "数据：主机上这张卡自己的文件 {f}", "get": "数据：本卡的本机服务 {w}", "call": "按钮「{l}」：调用 {w}",
             "prompt": "按钮「{l}」：发一条消息（每次先给你看全文）：{p}", "draft": "按钮「{l}」：把这段文字放进输入框（不发送）：{p}",
             "item": "（每一条上）", "href": "外链「{l}」：{u}", "jlink": "内链「{l}」：{u}", "repo": "本机服务的源码：{r} @ {c}",
             "src": "来自广场：{n} v{v}（{t}）", "cert": "Agent J 官方审核，签名已核验", "comm": "社群 · 待审核",
             "none": "没有按钮", "safe": "卡片拿不到密钥，按钮只会变成你确认后才发的消息，或调用上面列出的本机服务。"},
      "en": {"file": "Data: the card's own file on the host, {f}", "get": "Data: the card's service on the host, {w}", "call": "Button “{l}”: calls {w}",
             "prompt": "Button “{l}”: sends a message (shown to you in full each time): {p}", "draft": "Button “{l}”: puts this text in the message box (not sent): {p}",
             "item": " (on every item)", "href": "Web link “{l}”: {u}", "jlink": "Internal link “{l}”: {u}", "repo": "The service's source: {r} @ {c}",
             "src": "From the plaza: {n} v{v} ({t})", "cert": "reviewed by Agent J, signature verified", "comm": "community · pending review",
             "none": "No buttons", "safe": "The card cannot get your keys; a button only becomes a message you confirm, or calls the service listed above."}}


def _line(v: str) -> str:
    """Author text in the summary: one line, no control or format characters, the summary's own 「」 never closed."""
    t = "".join(" " if ord(c) < 32 or c in "\u2028\u2029" else c for c in str(v) if unicodedata.category(c) != "Cf")
    return re.sub(r"\s+", " ", t).strip().replace("「", "“").replace("」", "”")[:jcards.PROMPT_MAX]


def summary_text(doc: dict, lang: str, src: dict | None) -> str:
    T, s = _T["zh" if lang == "zh" else "en"], summary_of(doc)
    # author text: one line, no control / format characters, quoted (it can neither add nor imitate a summary line)
    pick = lambda v: "「" + _line(v.get(lang) or v.get("en") or v.get("zh") if isinstance(v, dict) else str(v)) + "」"  # noqa: E731
    out = [T["src"].format(n=src["name"], v=src["version"], t=T["cert"] if src.get("certified") else T["comm"])] if src else []
    out.append(T["file"].format(f=s["data"]["file"]) if "file" in s["data"] else T["get"].format(w=s["data"]["get"]))
    for items, tail in ((s["buttons"], ""), (s["itemButtons"], T["item"])):
        for b in items:
            if "call" in b:
                out.append(T["call"].format(l=pick(b["label"]), w=b["call"]) + tail)   # where: built by the host from checked fields
            else:
                out.append(T["draft" if b["draft"] else "prompt"].format(l=pick(b["label"]), p=pick(b["prompt"])) + tail)
    if not s["buttons"] and not s["itemButtons"]:
        out.append(T["none"])
    for x in s["links"]:
        out.append(T["href" if "href" in x else "jlink"].format(l=pick(x["label"]), u=x.get("href") or x.get("jlink")))   # href / jlink: checked shapes, one line
    if s["server"] and s["server"]["repo"]:
        out.append(T["repo"].format(r=s["server"]["repo"], c=s["server"]["ref"]))
    out.append(T["safe"])
    return "\n".join(out)


# ---------------------------------------------------------------- where an installed card came from
def _plaza_file(root) -> pathlib.Path:
    return pathlib.Path(root) / "cards" / "plaza.json"          # NOT under agentperm: the fenced Agent cannot write it


def sources(root) -> dict:
    try:
        raw, cut = jcards._read_fd(os.open(_plaza_file(root), os.O_RDONLY | jcards._NOFOLLOW | getattr(os, "O_NONBLOCK", 0)), 256 * 1024)
        obj = json.loads(raw or b"{}") if not cut else {}
        return {k: [r for r in v if isinstance(r, dict)] for k, v in obj.items() if isinstance(k, str) and isinstance(v, list)} if isinstance(obj, dict) else {}
    except (OSError, ValueError):
        return {}


def _card_sha(doc: dict) -> str:
    return hashlib.sha256(json.dumps(doc, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def source(root, cid: str, doc: dict | None = None) -> dict | None:
    """The plaza record of this card's installed version (None: not from the plaza); `unknown` when its bytes match none."""
    rows = sources(root).get(cid)
    if not rows:
        return None
    if doc is None:
        return rows[-1]
    sha = _card_sha(doc)
    return next((r for r in reversed(rows) if r.get("card_sha") == sha), {"name": rows[-1].get("name", "?"), "version": "?", "certified": False, "unknown": True})


def _save_sources(root, allrows: dict) -> None:
    p = _plaza_file(root)
    p.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    tmp = p.with_name(f".plaza.{os.getpid()}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | jcards._NOFOLLOW, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(allrows, fh, ensure_ascii=False, indent=1)
    os.replace(tmp, p)


def approved(root, cid: str, doc: dict, rows: dict | None = None) -> bool:
    """A plaza card may be on only when the owner approved the digest of the card as it is now (its own version's record)."""
    sha = _card_sha(doc)
    rec = next((r for r in reversed((rows if rows is not None else sources(root)).get(cid) or []) if r.get("card_sha") == sha), None)
    return bool(rec) and rec.get("approved") == digest(doc)


def _locked(root):
    from .state import State
    return State(pathlib.Path(root)).file_lock("card-plaza")


def approve(root, cid: str, doc: dict) -> bool:
    """Record that the owner read this version's summary. False when this exact version has no plaza record."""
    with _locked(root):
        allrows, sha = sources(root), _card_sha(doc)
        rec = next((r for r in reversed(allrows.get(cid) or []) if r.get("card_sha") == sha), None)
        if rec is None:
            return False
        rec["approved"] = digest(doc)
        _save_sources(root, allrows)
    return True


def unapprove(root, cid: str) -> None:
    """A version change (rollback / replace): every earlier approval of this card goes; the owner reads it again."""
    with _locked(root):
        allrows = sources(root)
        for r in allrows.get(cid) or []:
            r.pop("approved", None)
        _save_sources(root, allrows)


def needs_review(root, cid: str) -> bool:
    c = jcards.find(root, cid)
    return bool(c and not c["official"] and source(root, cid))


# ---------------------------------------------------------------- the 上线关键点 check
def preflight(files: dict) -> list:
    """{path: bytes} of a card package (manifest.json excluded) → problems ([] = may go out)."""
    probs = []
    raw = files.get("card/card.json")
    doc, errs = jcards.parse(raw) if raw is not None and len(raw) <= jcards.MANIFEST_MAX else (None, [jcards._m("size", "card.json", "", "card/card.json missing or > 16 KiB")])
    probs += [f"card.json {e['path']}: {e['en']}" for e in errs]
    if doc is None or errs:
        return probs or ["card.json"]
    want = doc["data"].get("file")
    extra = sorted(p for p in files if p not in FILES_OK and p != f"card/sample/{want}")
    if extra:
        probs.append("only README.md, card/card.json and card/sample/<data file> may ship: " + ", ".join(extra[:5]))
    if "README.md" not in files:
        probs.append("README.md is missing")
    srv = doc.get("server")
    if isinstance(srv, dict) and not (srv.get("repo") and srv.get("ref")):
        probs.append("a card with a server must name server.repo + server.ref (a GitHub repository and its 40-hex commit)")
    sample = files.get(f"card/sample/{want}") if want else None
    items = []
    if sample is not None:
        hits = set(privacy.redact_with_report(sample.decode("utf-8", "replace"))[1]) - jcards.BENIGN_HITS
        if hits:
            probs.append("the sample holds something that looks like a key or private data: " + ", ".join(sorted(hits)))
        if doc["template"] == "checklist":
            items, bad = jcards._items(sample)
            if bad:
                probs.append("the checklist sample is not valid JSON items")
        else:
            try:
                sample.decode("utf-8")
            except UnicodeDecodeError:
                probs.append("the notes sample is not UTF-8 text")
    card = {"id": doc["id"], "doc": doc}
    for lang in ("zh", "en"):
        for a in doc.get("actions", []) + doc.get("itemActions", []):
            if "prompt" not in a:
                continue
            item = items[0] if items and a in doc.get("itemActions", []) else ({"id": "i1", "text": "x", "done": False} if a in doc.get("itemActions", []) else None)
            msg = jcards.render(card, a["prompt"], lang, "/nonexistent", item)
            if not msg.strip() or len(msg) > jcards.PROMPT_MAX + 64:
                probs.append(f"button {a['id']} ({lang}) does not render a readable message")
    return probs


# ---------------------------------------------------------------- pack / install / rollback
def pack(root, cid: str, dest) -> dict:
    """One of the owner's cards → a plaza package folder (manifest.json, README.md, card/…). Sample only, never the data."""
    c = jcards.find(root, cid)
    if not c:
        return {"ok": False, "why": "not_found"}
    if c["official"]:
        return {"ok": False, "why": "official"}
    dest = pathlib.Path(dest).expanduser()
    if dest.exists() and any(dest.iterdir()):
        return {"ok": False, "why": "not_empty"}
    doc = c["doc"]
    files = {"card/card.json": jcards._read_file(c["dir"] / "card.json", jcards.MANIFEST_MAX) or b""}
    want = doc["data"].get("file")
    if want:
        sample = jcards._read_file(c["dir"] / "sample" / want, jcards.DATA_MAX)
        if sample is not None:
            files[f"card/sample/{want}"] = sample
    pick = lambda v, lang: v.get(lang) or v.get("en") or v.get("zh")  # noqa: E731
    files["README.md"] = ("# " + pick(doc["name"], "en") + " / " + pick(doc["name"], "zh") + "\n\n" + pick(doc["description"], "en") + "\n\n"
                          + pick(doc["description"], "zh") + "\n\n## What it can do / 能做什么\n\n" + summary_text(doc, "en", None) + "\n\n"
                          + summary_text(doc, "zh", None) + "\n\nInstall / 安装: `agentj plaza install " + doc["id"] + "`\n").encode()
    probs = preflight(files)
    if probs:
        return {"ok": False, "why": "preflight", "problems": probs}
    manifest = {"schema_version": "agentj.catalog/v1", "name": doc["id"], "type": "card", "version": _semver(doc["version"]),
                "title_zh": pick(doc["name"], "zh"), "title_en": pick(doc["name"], "en"), "summary_zh": pick(doc["description"], "zh"),
                "summary_en": pick(doc["description"], "en"), "tags": ["card"], "category": "data", "entry": "card/card.json",
                "install": {}, "requires": {}}
    for p, b in {**files, "manifest.json": (json.dumps(manifest, ensure_ascii=False, indent=1) + "\n").encode()}.items():
        f = dest / p
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(b)
    return {"ok": True, "dest": str(dest), "files": sorted(files) + ["manifest.json"]}


def install(root, files: dict, src: dict) -> dict:
    """A checked card package → applied switched OFF; its plaza record kept. → jcards.apply's answer."""
    probs = preflight(files)
    if probs:
        return {"ok": False, "why": "preflight", "problems": probs}
    doc = json.loads(files["card/card.json"])
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="agentj-card-"))
    try:
        (tmp / "card").mkdir()
        (tmp / "card" / "card.json").write_bytes(files["card/card.json"])
        for p, b in files.items():
            if p.startswith("card/sample/"):
                (tmp / "card" / "sample").mkdir(exist_ok=True)
                (tmp / "card" / "sample" / p.rsplit("/", 1)[1]).write_bytes(b)
        r = jcards.apply(root, tmp / "card", on=False)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if r.get("ok"):
        with _locked(root):
            allrows = sources(root)
            rows = [{k: v for k, v in x.items() if k != "approved"} for x in allrows.get(doc["id"], []) if x.get("card_sha") != _card_sha(doc)]
            rows.append({"name": src["name"], "version": src["version"], "sha256": src["sha256"], "certified": bool(src.get("certified")),
                         "card_sha": _card_sha(doc)})
            allrows[doc["id"]] = rows[-SOURCES_KEEP:]
            _save_sources(root, allrows)
    return r


def rollback(root, cid: str) -> dict:
    """The newest sleeping version of one of the owner's cards comes back (switched off); the current one sleeps."""
    c = jcards.find(root, cid)
    if not c or c["official"]:
        return {"ok": False, "why": "not_found"}
    try:
        with jcards._dirfd(root, ("cards", "active")) as afd, jcards._dirfd(root, ("cards", "dormant")) as dfd:
            names = sorted((n for n in os.listdir(dfd) if jcards.DORMANT_RE.fullmatch(n) and re.fullmatch(r"\d{8}-\d{6}-" + re.escape(cid) + r"(-\d+)?", n)), reverse=True)
            for n in names:
                try:
                    nfd = os.open(n, jcards._DIRFLAGS, dir_fd=dfd)
                    try:
                        raw, cut = jcards._read_fd(os.open("card.json", os.O_RDONLY | jcards._NOFOLLOW | getattr(os, "O_NONBLOCK", 0), dir_fd=nfd), jcards.MANIFEST_MAX)
                    finally:
                        os.close(nfd)
                except OSError:
                    continue
                doc, errs = jcards.parse(None if cut else raw)
                if doc and not errs and doc["id"] == cid:
                    slept = jcards._sleep_name(dfd, cid)     # current → dormant, then the chosen one back; prune last
                    os.replace(cid, slept, src_dir_fd=afd, dst_dir_fd=dfd)
                    os.replace(n, cid, src_dir_fd=dfd, dst_dir_fd=afd)
                    jcards._prune(dfd)
                    break
            else:
                return {"ok": False, "why": "nothing_to_roll_back"}
    except OSError:
        return {"ok": False, "why": "link"}
    s = jcards.switches(root)
    s[cid] = False
    jcards._save_switches(root, s)
    if source(root, cid):
        unapprove(root, cid)                  # off until the owner reads this version's summary again
    return {"ok": True, "id": cid, "version": doc["version"], "dormant": slept, "on": False}
