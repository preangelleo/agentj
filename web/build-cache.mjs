// Release the two styles and two language modules with the previous release's exact bytes.
import {createHash} from 'node:crypto';
import {gzipSync, gunzipSync} from 'node:zlib';
import {readFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';

const sha = bytes => createHash('sha256').update(bytes).digest('hex');
export const indexName = 'cache-generations.json';
export const cachePath = /^(?:(?:app|brand\/base)\.[0-9a-f]{64}\.css\.gz|js\/locale-(?:en|zh)\.[0-9a-f]{64}\.js)$/;
export function addCacheAssets(files, dictionaries, version, previousDir) {
  const names = [];
  let html = files.get('index.html').toString();
  for (const path of ['app.css', 'brand/base.css']) {
    const bytes = files.get(path), digest = sha(bytes);
    const name = path.replace('.css', '.' + digest + '.css.gz');
    const href = new RegExp('href="' + path.replace('.', '\\.') + '(?:\\?rev=[0-9a-f]{64})?"', 'g');
    html = html.replace(href, 'href="' + path + '?rev=' + digest + '"');
    names.push(name);
    files.set(name, gzipSync(bytes, {level: 9}));
  }
  files.set('index.html', Buffer.from(html));
  const urls = {}, common = {};
  for (const [lang, words] of Object.entries(dictionaries)) {
    const data = Buffer.from('export default ' + JSON.stringify(words) + ';\n');
    const name = 'js/locale-' + lang + '.' + sha(data) + '.js';
    names.push(name);
    files.set(name, data);
    urls[lang] = './' + name.slice(3);
    // These features deliberately search both languages, even before switching language.
    common[lang] = Object.fromEntries(Object.entries(words).filter(([key]) =>
      /^(?:bots|ix|ixkw|ixges|ixw|ixgrp|device|p0280\.harness|p0284\.bio|p539\.bio)\./.test(key)));
  }
  const imports = Object.entries(urls).map(([lang,url]) => '  ' + lang + ': retry => retry ? import(' + JSON.stringify(url + '?retry=') + ' + retry) : import(' + JSON.stringify(url) + ')');
  files.set('js/locale-assets.js', Buffer.from('// Generated by build.mjs.\nexport const loaders = {\n' + imports.join(',\n') + '\n};\nexport const common = ' + JSON.stringify(common) + ';\n'));
  const current = {version, paths: names.sort()};
  const oldPath = join(previousDir, indexName);
  const old = existsSync(oldPath) ? JSON.parse(readFileSync(oldPath, 'utf8')) : null;
  if (old && (!old.current || typeof old.current.version !== 'string')) throw Error('invalid cache generation index');
  const previous = old?.current.version === version ? old.previous : old?.current ?? null;
  if (previous) {
    if (!Array.isArray(previous.paths) || previous.paths.length !== 4) throw Error('invalid previous cache generation');
    const kinds = new Set(previous.paths.map(name => name.replace(/\.[0-9a-f]{64}\./, '.')));
    if (!['app.css.gz', 'brand/base.css.gz', 'js/locale-en.js', 'js/locale-zh.js'].every(name => kinds.has(name))) throw Error('incomplete previous cache generation');
    for (const name of previous.paths) {
      if (!cachePath.test(name)) throw Error('invalid previous cache path');
      if (files.has(name)) continue;
      const bytes = readFileSync(join(previousDir, name));
      const digest = name.match(/\.([0-9a-f]{64})\./)[1];
      if (sha(name.endsWith('.gz') ? gunzipSync(bytes) : bytes) !== digest) throw Error('previous cache digest mismatch: ' + name);
      files.set(name, bytes);
    }
  }
  files.set(indexName, Buffer.from(JSON.stringify({current, previous}, null, 2) + '\n'));
}
