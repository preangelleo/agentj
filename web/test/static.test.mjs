const DICT = dictionaries();
const ph = (s) => (s.match(/\{\w+\}/g) || []).sort().join(' ');
test('i18n: zh and en have the same keys and placeholders; i18n.js and index.html are built from them', () => {
  assert.deepEqual(Object.keys(DICT.en).sort(), Object.keys(DICT.zh).sort());
  for (const k of Object.keys(DICT.zh)) {
    assert.equal(ph(DICT.en[k]), ph(DICT.zh[k]), `placeholders differ for ${k}`);
    assert.ok(DICT.zh[k].trim() && DICT.en[k].trim(), `empty string for ${k}`);
    assert.equal((DICT.zh[k].match(/`/g) || []).length % 2, 0, `unbalanced backticks zh ${k}`);
    assert.equal((DICT.en[k].match(/`/g) || []).length % 2, 0, `unbalanced backticks en ${k}`);
  }
  assert.equal(read(pub('i18n.js')), i18nModule(DICT), 'public/i18n.js is stale — run build.mjs');
  assert.equal(HTML, syncHtml(HTML, DICT.zh), 'index.html Chinese text differs from web.zh.json — run build.mjs');
  for (const m of HTML.matchAll(/data-i18n="([\w.]+)"/g)) assert.ok(DICT.zh[m[1]], `index.html: unknown key ${m[1]}`);
  for (const m of APP.matchAll(/\bt\('([\w.]+)'/g)) {
    if (m[1].endsWith('.')) assert.ok(Object.keys(DICT.zh).some((k) => k.startsWith(m[1])), `app.js: no keys under ${m[1]}`);
    else assert.ok(DICT.zh[m[1]], `app.js: unknown key ${m[1]}`);
  }
});

