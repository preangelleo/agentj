// glossary.json "forbidden" patterns are Python regexes: a leading (?i) becomes the JS i flag; (?i:…) groups are native
const GLOSSARY = existsSync(GLOSSARY_FILE) ? JSON.parse(read(GLOSSARY_FILE)) : null;
const NO_GLOSSARY = !GLOSSARY && 'no agentjarvis/i18n (public export)';
const jsRe = (p) => (p.startsWith('(?i)') ? new RegExp(p.slice(4), 'i') : new RegExp(p));
test('i18n: no internal terms or banned words in either dictionary, the page text or app.js literals', { skip: NO_GLOSSARY }, () => {
  const visible = HTML.replace(/<script[\s\S]*?<\/script>|<[^>]+>/g, ' ');
  const sources = [...Object.entries(DICT.zh).map(([k, v]) => [`zh ${k}`, v]), ...Object.entries(DICT.en).map(([k, v]) => [`en ${k}`, v]), ['index.html text', visible]];
  for (const f of GLOSSARY.forbidden) {
    const re = jsRe(f.pattern);
    for (const [where, text] of sources) assert.doesNotMatch(text, re, `${where}: internal term /${f.pattern}/ — say 「${f.say_zh}」 / "${f.say_en}"`);
  }
  for (const [k, v] of Object.entries(DICT.zh)) {
    for (const w of GLOSSARY.banned_words_zh) assert.ok(!v.includes(w), `zh ${k}: banned word ${w}`);
    for (const p of GLOSSARY.banned_patterns_zh) assert.doesNotMatch(v, new RegExp(p), `zh ${k}: banned pattern ${p}`);
  }
  // every user-visible Chinese string lives in the dictionary: app.js code has no Chinese except the device label sent to
  // the host ("网页 · Chrome" is data for the computer's device list) and comments
  const code = APP.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
  const cjk = [...new Set(code.match(/[㐀-鿿]+/g) || [])];
  assert.ok(cjk.includes('网页') && cjk.every((w) => ['浏览器', '网页'].includes(w)), `app.js has UI Chinese outside the dictionary: ${cjk.join(' ')}`);
});

test('i18n: the forbidden-term check itself works (positive control)', { skip: NO_GLOSSARY }, () => {
  const planted = ['Noise 握手', '急停', 'alpha', 'harness', 'Zero Access'];
  for (const s of planted) assert.ok(GLOSSARY.forbidden.some((f) => jsRe(f.pattern).test(s)), `no forbidden pattern catches ${s}`);
});

