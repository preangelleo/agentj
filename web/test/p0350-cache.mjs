// Real Worker, complete preview collections, and held Chromium/WebKit pages on root and seat routes.
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {createHash} from 'node:crypto';
import {mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, dirname, resolve, extname} from 'node:path';
import {createRequire} from 'node:module';
import {dictionaries, manifest, sourceFiles} from '../build.mjs';
import {addCacheAssets, cachePath} from '../build-cache.mjs';
import {freezePreview} from '../preview-bundle.mjs';
import {handle, previewBundle, PREVIEW_BOOTSTRAP} from '../worker.ts';

const pw=createRequire(import.meta.url)(process.env.AJ_PLAYWRIGHT_MODULE || '/tmp/aj-webmcp-playwright/node_modules/playwright');
const temp=mkdtempSync(join(tmpdir(),'aj-cache-release-')), result={releases:[], journeys:[]};
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const root=resolve(process.env.P0350_OUT || 'reports/qa/p0350-cache');
mkdirSync(root,{recursive:true});

function generation(label, previous) {
  const files=sourceFiles(), d=dictionaries(), dir=join(temp,label), bundles=join(temp,'bundles');
  for(const key of files.keys())if(cachePath.test(key))files.delete(key);
  for(const css of ['app.css','brand/base.css'])files.set(css,Buffer.concat([files.get(css),Buffer.from('\n/* '+label+' */\n')]));
  for(const lang of ['zh','en']) d[lang]['cache.revision']=lang+' '+label;
  addCacheAssets(files,d,label,previous?.dir || dir);
  files.set('.aj/preview/bootstrap.js',Buffer.from(PREVIEW_BOOTSTRAP));
  const m={...manifest(files),version:label,preview:{channel:'preview'}};
  const json=JSON.stringify(m,null,2)+'\n';
  files.set('version.json',Buffer.from(json));
  files.set('version.js',Buffer.from('// generated by build.mjs — do not edit\nexport default '+json.trimEnd()+';\n'));
  for(const [path,bytes] of files){mkdirSync(dirname(join(dir,path)),{recursive:true});writeFileSync(join(dir,path),bytes);}
  const pin=freezePreview(dir,bundles), bundle=readFileSync(join(bundles,pin.bundleSha256+'.json'));
  assert.ok(pin.bytes<=24*1024*1024);
  result.releases.push({label,bytes:pin.bytes,paths:files.size});
  return {files,pin,bundle,dir};
}
const mime = {'.js':'text/javascript','.mjs':'text/javascript','.css':'text/css','.json':'application/json','.html':'text/html','.svg':'image/svg+xml','.woff2':'font/woff2'};
try {
  const a=generation('A'), b=generation('B',a), c=generation('C',b);
  const index=g=>JSON.parse(g.files.get('cache-generations.json')).current;
  assert.ok(index(a).paths.every(p=>b.files.has(p) && !c.files.has(p)));
  assert.ok(index(b).paths.every(p=>c.files.has(p)));
  let active=a;
  const requests=[];
  const env={WEB_HOST:'127.0.0.1',RELAY_URL:'wss://relay.test',ASSETS:{async fetch(req){
    const path=decodeURIComponent(new URL(req.url).pathname.slice(1))||'index.html';
    if(path==='.preview/'+active.pin.bundleSha256+'.json')return new Response(active.bundle);
    const bytes=active.files.get(path);
    return new Response(bytes||'missing',{status:bytes?200:404,headers:{'content-type':mime[extname(path)]||'application/octet-stream'}});
  }}};
  active=b;
  assert.ok(await previewBundle(new Request('https://m.agentj.app/'),env,b.pin),'candidate verifies via the real Worker preview reader');
  const server=createServer(async(req,res)=>{
    try{
      const response=await handle(new Request('http://127.0.0.1:'+server.address().port+req.url,{method:req.method,headers:req.headers}),env);
      requests.push({url:req.url,status:response.status,cache:response.headers.get('cache-control')});
      res.writeHead(response.status,Object.fromEntries(response.headers));res.end(Buffer.from(await response.arrayBuffer()));
    }catch(error){res.writeHead(500);res.end(String(error));}
  });
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const origin='http://127.0.0.1:'+server.address().port;
  try{
    for(const engine of ['chromium','webkit']){
      const browser=await pw[engine].launch(engine==='chromium'?{executablePath:process.env.CHROMIUM||'/usr/bin/chromium',args:['--no-sandbox']}:{});
      try{
        for(const route of ['/','/abcdefgh/']){
          const context=await browser.newContext({serviceWorkers:'block'});
          try{
            await context.route('**/*',r=>r.request().url().startsWith(origin)?r.continue():r.abort());
            active=a;const start=requests.length, held=await context.newPage();
            await held.goto(origin+route+'?lang=zh');
            const word=page=>page.evaluate(async()=> (await import('./js/t.js')).t('cache.revision'));
            assert.equal(await word(held),'zh A');
            const oldCss=await held.locator('link[rel=stylesheet][href^="app.css"]').getAttribute('href');
            const oldCssBytes=await (await fetch(origin+route+oldCss)).arrayBuffer();
            assert.equal(sha(Buffer.from(oldCssBytes)),sha(a.files.get('app.css')));
            assert.equal(requests.slice(start).some(x=>x.url.includes('locale-en.')),false,'inactive language stays unloaded until requested');
            active=b;const fresh=await context.newPage();await fresh.goto(origin+route+'?lang=en');
            assert.equal(await word(fresh),'en B');
            await fresh.screenshot({path:join(root,engine+'-'+(route==='/'?'root':'seat')+'-fresh.png')});
            // Fail requesting the optional old language once; keep the text and the stored selection usable.
            const oldEn=index(a).paths.find(p=>p.startsWith('js/locale-en.'));
            await held.route('**/'+oldEn,r=>r.abort());
            assert.equal(await held.evaluate(()=>window.AJLang.set('en')),'zh');
            assert.equal(await word(held),'zh A');
            await held.unroute('**/'+oldEn);
            await fresh.bringToFront();await held.bringToFront();
            assert.equal(await held.evaluate(()=>window.AJLang.set('en')),'en');
            assert.equal(await word(held),'en A');
            await held.screenshot({path:join(root,engine+'-'+(route==='/'?'root':'seat')+'-held.png')});
            assert.equal(sha(Buffer.from(await (await fetch(origin+route+oldCss)).arrayBuffer())),sha(a.files.get('app.css')));
            await held.reload();assert.equal(await word(held),'en B');
            const css=await held.locator('link[rel=stylesheet][href^="app.css"]').getAttribute('href');
            assert.notEqual(css,oldCss);
            const latest=await fetch(origin+route+css);
            assert.match(latest.headers.get('cache-control'),/immutable/);
            assert.equal(sha(Buffer.from(await latest.arrayBuffer())),sha(b.files.get('app.css')));
            assert.match((await fetch(origin+route)).headers.get('cache-control'),/no-store/);
            assert.match((await fetch(origin+route+oldEn)).headers.get('cache-control'),/immutable/);
            const unknown=await fetch(origin+route+'app.css?rev='+'a'.repeat(64));
            assert.equal(unknown.status,404);assert.doesNotMatch(unknown.headers.get('cache-control')||'',/immutable/);
            result.journeys.push({engine,route,heldLanguage:'en A',freshLanguage:'en B',foregroundReload:'en B',missingLanguage:'zh A'});
          }finally{await context.close();}
        }
      }finally{await browser.close();}
    }
  }finally{server.closeAllConnections();await new Promise(r=>server.close(r));}
  console.log(JSON.stringify(result));writeFileSync(join(root,'result.json'),JSON.stringify(result,null,2)+'\n');
}finally{rmSync(temp,{force:true,recursive:true});}
